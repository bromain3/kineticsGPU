"""
Backward (implicit) Euler integrator with batched GPU support in PyTorch.
Features:
- Implicit backward Euler with Newton iterations
- Linear solver options: dense LU (via full Jacobian) or GMRES implemented in a batched/vectorized way
- Simple preconditioners: identity (default), Jacobi (diagonal) computed via autograd, or user-provided M^{-1} function
- Works with batched systems (B, N) on GPU/CPU
- Example usages at the bottom: linear system test and small nonlinear system

Notes:
- For large systems, avoid dense LU; prefer GMRES with jacobi preconditioning.
- The integrator expects the RHS f(x, t) to accept batched x of shape (B, N) and return (B, N).
- The code uses torch.autograd.functional.jvp for Jacobian-vector products; ensure requires_grad on inputs.

Author: Generated by ChatGPT (GPT-5 Thinking mini) for the user.
"""


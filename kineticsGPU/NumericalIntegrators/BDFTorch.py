"""
Backward (implicit) Euler integrator with batched GPU support in PyTorch.
Features:
- Implicit backward Euler with Newton iterations
- Linear solver options: dense LU (via full Jacobian) or GMRES implemented in a batched/vectorized way
- Simple preconditioners: identity (default), Jacobi (diagonal) computed via autograd, or user-provided M^{-1} function
- Works with batched systems (B, N) on GPU/CPU
- Example usages at the bottom: linear system test and small nonlinear system

Notes:
- For large systems, avoid dense LU; prefer GMRES with jacobi preconditioning.
- The integrator expects the RHS f(x, t) to accept batched x of shape (B, N) and return (B, N).
- The code uses torch.autograd.functional.jvp for Jacobian-vector products; ensure requires_grad on inputs.

Author: Generated by ChatGPT (GPT-5 Thinking mini) for the user.
"""

import math
from typing import Callable, Optional, Tuple
import torch

Tensor = torch.Tensor


# TODO: investigate GPU memory increasing during integration
def _ensure_batch_dim(x: Tensor) -> Tensor:
    if x.dim() == 1:
        return x.unsqueeze(0)
    return x


class BackwardEulerIntegrator:
    def __init__(self,
                 f: Callable[[Tensor, float], Tensor],
                 device: Optional[torch.device] | str = None,
                 dtype: Optional[torch.dtype] = None,
                 newton_tol: float = 1e-6,
                 newton_maxiter: int = 20,
                 gmres_tol: float = 1e-6,
                 gmres_maxiter: int = 50,
                 gmres_restart: int = 20,
                 verbose: bool = False):
        """
        f: function f(x, t) -> (B, N)
        device, dtype: where to allocate tensors
        newton_*: Newton solver settings
        gmres_*: GMRES settings
        """
        self.f = f
        self.device = device or torch.device('cuda' if torch.cuda.is_available() else 'cpu')
        self.dtype = dtype or torch.float32
        self.newton_tol = newton_tol
        self.newton_maxiter = newton_maxiter
        self.gmres_tol = gmres_tol
        self.gmres_maxiter = gmres_maxiter
        self.gmres_restart = gmres_restart
        self.verbose = verbose

    def step(self,
             x: Tensor,
             t: float,
             h: float,
             method: str = 'gmres',
             precond: str = 'identity',
             m_inv_fn: Optional[Callable[[Tensor], Tensor]] = None) -> Tensor:
        """
        Take one implicit backward Euler step from (x, t) with step h.
        x: (B, N) or (N,)
        method: 'gmres' or 'dense'
        precond: 'identity' or 'jacobi' or 'user' (if 'user' then m_inv_fn must be provided)
        m_inv_fn: function M_inv(vec) -> vec with shape (B, N)
        Returns x_next of shape (B, N)
        """
        x_b = _ensure_batch_dim(x).to(device=self.device, dtype=self.dtype)
        B, N = x_b.shape
        t_new = t + h

        # initial guess: explicit Euler or previous state
        xk = x_b + h * self.f(x_b, t) #TODO: maybe do both, and start form the one with the best converged newton ?

        # choose preconditioner
        if precond == 'identity':
            m_inv_fn_eff = lambda v: v
        elif precond == 'jacobi':
            # compute diagonal of J = I - h * df/dx at xk (batched)
            diag = self._estimate_jacobian_diag(xk, t_new, h)
            # avoid zeros
            diag = diag.clone()
            diag[diag == 0] = 1.0
            m_inv_fn_eff = lambda v: v / diag
        elif precond == 'user':
            if m_inv_fn is None:
                raise ValueError("m_inv_fn must be provided when precond='user'")
            m_inv_fn_eff = m_inv_fn
        else:
            raise ValueError(f"Unknown precond {precond}")

        # Newton iterations
        for nit in range(self.newton_maxiter):
            # compute residual WITHOUT keeping a history linked aux solves
            xk = xk.detach()  # detach before computing residual
            fxk = self.f(xk, t_new)  # no grad history needed for residual
            # Residual F = xk - x - h * f(xk, t+h)
            F = xk - x_b - h * fxk  # shape (B, N)
            # if we need a grad-enabled version for Jacobian-vector products inside solvers,
            # we'll create a fresh detached.requires_grad_(True) inside those solvers.
            res_norm = F.detach().norm(dim=1).max().item()
            if self.verbose:
                print(f"Newton iter {nit}, max residual norm = {res_norm:.3e}")
            if res_norm < self.newton_tol:
                break

            # Linear solve (I - h J_f) dx = -F
            if method == 'dense':
                dx = self._dense_solve(xk, t_new, h, -F)
            elif method == 'gmres':
                dx = self._gmres_solve(xk, t_new, h, -F, m_inv_fn_eff)
            else:
                raise ValueError(f"Unknown linear solver method {method}")

            # update
            xk = (xk + dx).detach()

        return xk.detach()

    def _estimate_jacobian_diag(self, x: Tensor, t: float, h: float, eps: float = 1e-6) -> Tensor:
        """
        Estimate diag of J = I - h * df/dx using directional JVP of basis vectors.
        This computes the diagonal by computing J e_i for each i and taking component i.
        For large N this is expensive, but batched on GPU it's often acceptable.
        Returns tensor shape (B, N)
        """
        B, N = x.shape
        # build identity basis in device/dtype
        eye = torch.eye(N, device=self.device, dtype=self.dtype)  # (N,N)
        # We'll compute jvp for each basis vector; use jvp over batch: repeat x for each basis
        # To avoid a double loop, we do per-batch jvp by expanding vectors: result shape (N, B, N)
        # But torch.autograd.functional.jvp expects function that maps (B,N) -> (B,N). We'll compute jvp per basis vector in loop over N.
        diag = torch.zeros_like(x)
        for i in range(N):
            v = eye[i].unsqueeze(0).expand(B, -1)  # (B,N)
            # jvp of f: compute df_dx @ v
            _, jvp = torch.autograd.functional.jvp(lambda z: self.f(z, t), x, v, create_graph=False)
            # diagonal contribution is 1 - h * (df/dx)_{ii}
            diag[:, i] = 1.0 - h * jvp[:, i]
        return diag

    def _dense_solve(self, x: Tensor, t: float, h: float, rhs: Tensor) -> Tensor:
        """
        Build full Jacobian and solve using LU (batched)
        J = I - h * df/dx
        rhs shape (B, N)
        returns dx of shape (B, N)
        """
        B, N = x.shape
        # compute full jacobian per batch using autograd.functional.jacobian
        Js = torch.zeros((B, N, N), device=self.device, dtype=self.dtype)
        for b in range(B):
            xb = x[b].unsqueeze(0).requires_grad_(True)
            # jacobian: (N, N)
            Jf = torch.autograd.functional.jacobian(lambda z: self.f(z, t)[0], xb)[0]
            Js[b] = torch.eye(N, device=self.device, dtype=self.dtype) - h * Jf
        # solve batched linear systems
        # torch.linalg.solve supports batched solve
        dx = torch.linalg.solve(Js, rhs.unsqueeze(-1)).squeeze(-1)
        return dx

    def _gmres_solve(self, x: Tensor, t: float, h: float, rhs: Tensor, m_inv_fn: Callable[[Tensor], Tensor]) -> Tensor:
        """
        Batched GMRES solver for (I - h J) dx = rhs
        rhs: (B, N)
        returns dx: (B, N)
        This implementation does a restarted GMRES with Arnoldi, vectorized over batch.
        """
        B, N = rhs.shape
        # matvec: apply A @ v = (I - h J) v, computed with Jv via jvp on f
        x_for_jvp_base = x.detach()
        def matvec(v: Tensor) -> Tensor:
            v_ = v.detach()
            # v: (B, N)
            # compute jvp of f at x: jvp = J_f @ v
            x_local = x_for_jvp_base.requires_grad_(True)
            _, jvp = torch.autograd.functional.jvp(lambda z: self.f(z, t), x_local, v_, create_graph=False)
            return v_ - h * jvp

        # initialize solution
        x_sol = torch.zeros_like(rhs)
        r = rhs.detach() - matvec(x_sol)  # initial residual = rhs
        # apply preconditioner
        z = m_inv_fn(r).detach()
        beta = torch.norm(z, dim=1)
        # handle zero betas
        beta = torch.where(beta == 0, torch.tensor(1.0, device=self.device, dtype=self.dtype), beta)

        max_restarts = math.ceil(self.gmres_maxiter / self.gmres_restart)

        for restart in range(max_restarts):
            # Arnoldi: build Krylov subspace up to m = gmres_restart
            m = min(self.gmres_restart, self.gmres_maxiter - restart * self.gmres_restart)
            V = torch.zeros((B, m + 1, N), device=self.device, dtype=self.dtype)
            H = torch.zeros((B, m + 1, m), device=self.device, dtype=self.dtype)
            g = torch.zeros((B, m + 1), device=self.device, dtype=self.dtype)

            # initial v0 = z / beta
            v0 = (z / beta.unsqueeze(1)).detach()
            V[:, 0, :] = v0
            g[:, 0] = beta

            for j in range(m):
                vj = V[:, j, :].detach()
                w = matvec(vj).detach()
                # apply preconditioner
                w = m_inv_fn(w).detach()
                # Modified Gram-Schmidt
                for i in range(j + 1):
                    vi = V[:, i, :].detach()
                    hij = torch.sum(w * vi, dim=1)
                    H[:, i, j] = hij
                    w = w - hij.unsqueeze(1) * vi
                hj1 = torch.norm(w, dim=1)
                H[:, j + 1, j] = hj1
                # avoid division by zero
                nonzero = hj1 != 0
                if nonzero.any():
                    V[nonzero, j + 1, :] = (w[nonzero] / hj1[nonzero].unsqueeze(1))
                else:
                    V[:, j + 1, :] = 0.0

                # Apply Givens rotations to H column j to maintain upper triangular form.
                # For simplicity and vectorization we solve least-squares at the end using torch.linalg.lstsq

            # Solve small least squares for each batch: minimize ||H y - g||
            # reshape H to (B, (m+1), m)
            # We want y of shape (B, m)
            # Use torch.linalg.lstsq per batch inside a loop (m is small)
            y = torch.zeros((B, m), device=self.device, dtype=self.dtype)
            for b in range(B):
                Hb = H[b, :m + 1, :m].detach()
                gb = g[b, :m + 1].detach()
                # least squares solve Hb @ y = gb
                # use torch.linalg.lstsq if available
                sol = torch.linalg.lstsq(Hb, gb.unsqueeze(1)).solution.squeeze(1)
                y[b, :] = sol

            # update solution
            # dx += V[:, :m, :].transpose(1,2) @ y
            # compute batch matmul: (B, N, m) @ (B, m) -> (B, N)
            V_nm = V[:, :m, :].permute(0, 2, 1).detach()  # (B, N, m)
            y_unsq = y.unsqueeze(-1)  # (B, m, 1)
            delta = torch.matmul(V_nm, y_unsq).squeeze(-1).detach()
            x_sol = (x_sol + delta).detach()

            # compute new residual
            r = (rhs.detach() - matvec(x_sol)).detach()
            res_norms = torch.norm(r, dim=1)
            if self.verbose:
                print(f"GMRES restart {restart}, max residual = {res_norms.max().item():.3e}")
            if res_norms.max().item() < self.gmres_tol:
                break

            # prepare next restart
            z = m_inv_fn(r).detach()
            beta = torch.norm(z, dim=1)
            beta = torch.where(beta == 0, torch.tensor(1.0, device=self.device, dtype=self.dtype), beta)

        return x_sol


